// Demo for the generated raylib bindings: bouncing balls, mouse, keyboard input.
import {
  InitWindow,
  CloseWindow,
  WindowShouldClose,
  BeginDrawing,
  EndDrawing,
  ClearBackground,
  DrawText,
  MeasureText,
  DrawFPS,
  DrawCircle,
  DrawCircleLines,
  DrawRectangle,
  DrawLineEx,
  IsKeyDown,
  GetKeyPressed,
  GetCharPressed,
  GetMousePosition,
  GetFrameTime,
  GetScreenWidth,
  GetScreenHeight,
  GetTime,
  Fade,
  SetTargetFPS,
  KEY_ESCAPE,
  KEY_SPACE,
  KEY_R,
} from "../gen/raylib";
import type { Vector2, Color } from "../gen/raylib";

interface Ball {
  pos: Vector2;
  vel: Vector2;
  radius: number;
  color: Color;
  phase: number;
}

const PALETTE: Color[] = [
  { r: 231, g: 111, b: 81, a: 255 },
  { r: 42, g: 157, b: 143, a: 255 },
  { r: 233, g: 196, b: 106, a: 255 },
  { r: 38, g: 70, b: 83, a: 255 },
  { r: 244, g: 162, b: 97, a: 255 },
];

function spawnBall(count: number): Ball {
  const c = PALETTE[count % PALETTE.length]!;
  return {
    pos: { x: 60 + (count * 137) % 680, y: 60 + (count * 251) % 330 },
    vel: { x: 120 + (count * 53) % 220, y: 90 + (count * 97) % 260 },
    radius: 10 + (count * 7) % 22,
    color: c,
    phase: count * 0.7,
  };
}

const balls: Ball[] = [];
for (let i = 0; i < 14; i++) balls.push(spawnBall(i));

let typed = "";
let pulse = 0;

InitWindow(800, 450, "raylib bindings — generated by scriptc");
SetTargetFPS(60);

while (WindowShouldClose() === false) {
  const dt = GetFrameTime();
  const w = GetScreenWidth();
  const h = GetScreenHeight();
  const t = GetTime();

  if (IsKeyDown(KEY_ESCAPE)) break;
  if (IsKeyDown(KEY_R)) {
    for (let i = 0; i < balls.length; i++) balls[i] = spawnBall(i);
    typed = "";
  }

  for (; ;) {
    const key = GetKeyPressed();
    if (key === 0) break;
  }
  for (; ;) {
    const ch = GetCharPressed();
    if (ch === 0) break;
    if (ch >= 32) typed += String.fromCharCode(ch);
    if (typed.length > 40) typed = typed.slice(1);
  }

  const mouse = GetMousePosition();
  pulse += dt;

  for (const b of balls) {
    b.pos.x += b.vel.x * dt;
    b.pos.y += b.vel.y * dt;
    if (b.pos.x < b.radius || b.pos.x > w - b.radius) {
      b.vel.x = -b.vel.x;
      b.pos.x = Math.min(Math.max(b.pos.x, b.radius), w - b.radius);
    }
    if (b.pos.y < b.radius || b.pos.y > h - b.radius) {
      b.vel.y = -b.vel.y;
      b.pos.y = Math.min(Math.max(b.pos.y, b.radius), h - b.radius);
    }
  }

  BeginDrawing();
  ClearBackground({ r: 30, g: 30, b: 40, a: 255 });

  // trail line from the mouse to the nearest ball
  let nearest = balls[0]!;
  let best = Infinity;
  for (const b of balls) {
    const dx = b.pos.x - mouse.x;
    const dy = b.pos.y - mouse.y;
    const d = dx * dx + dy * dy;
    if (d < best) { best = d; nearest = b; }
  }
  DrawLineEx(mouse, nearest.pos, 2, Fade({ r: 255, g: 255, b: 255, a: 255 }, 0.25));

  const breathe = 1 + 0.25 * Math.sin(t * 3);
  for (const b of balls) {
    DrawCircle(b.pos.x | 0, b.pos.y | 0, (b.radius * breathe) | 0, b.color);
    DrawCircleLines(b.pos.x | 0, b.pos.y | 0, (b.radius * breathe + 4) | 0, Fade(b.color, 0.5));
  }

  // mouse cursor ring
  DrawCircleLines(mouse.x | 0, mouse.y | 0, 12, { r: 255, g: 255, b: 255, a: 255 });

  DrawRectangle(0, 0, w, 34, { r: 0, g: 0, b: 0, a: 140 });
  const title = "raylib + TypeScript + scriptc — no Node inside";
  DrawText(title, (w - MeasureText(title, 18)) >> 1, 9, 18, { r: 255, g: 255, b: 255, a: 255 });

  DrawText("R: respawn    SPACE: pulse    ESC: exit", 12, h - 46, 14, { r: 170, g: 170, b: 180, a: 255 });
  DrawText("typed: " + (typed === "" ? "-" : typed), 12, h - 26, 14, { r: 233, g: 196, b: 106, a: 255 });
  DrawFPS(w - 90, 42);

  EndDrawing();

  void KEY_SPACE;
  void pulse;
}

CloseWindow();
